//! A live end-to-end run against the real service, through the real MCP stdio interface.
//!
//! Ignored by default. It needs an account with remote checks on, git, and a Rust toolchain
//! on PATH, and it makes about five remote runs:
//!
//! ```sh
//! MACHINESTREAM_E2E=1 MACHINESTREAM_API_KEY=... cargo test --test e2e_live -- --ignored --nocapture
//! ```
//!
//! The key is read from the environment only and is never printed.

mod support;

use std::path::{Path, PathBuf};
use std::time::Instant;

use serde_json::{json, Value};
use support::{git, text_of, McpClient};

fn write(path: &Path, text: &str) {
    std::fs::create_dir_all(path.parent().unwrap()).unwrap();
    std::fs::write(path, text).unwrap();
}

/// A tiny crate in its own git repository. The marker makes its tree unlike any earlier run's.
fn tiny_crate(dir: &Path, marker: u128) -> PathBuf {
    let project = dir.join("tiny-crate");
    write(
        &project.join("Cargo.toml"),
        "[package]\nname = \"tiny-crate\"\nversion = \"0.1.0\"\nedition = \"2021\"\n\n[dependencies]\n",
    );
    // A lockfile, as a real project has.
    write(
        &project.join("Cargo.lock"),
        "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"tiny-crate\"\nversion = \"0.1.0\"\n",
    );
    write(&project.join(".gitignore"), "target\n");
    write(&project.join("src/lib.rs"), &passing_source(marker));
    git(&project, &["init", "-q", "-b", "main"]);
    git(&project, &["add", "-A"]);
    git(&project, &["commit", "-q", "-m", "A tiny crate"]);
    project
}

fn passing_source(marker: u128) -> String {
    format!(
        "/// Marks this run: {marker}.\npub fn add(left: u64, right: u64) -> u64 {{\n    left + right\n}}\n\n#[cfg(test)]\nmod tests {{\n    use super::*;\n\n    #[test]\n    fn it_adds() {{\n        assert_eq!(add(2, 2), 4);\n    }}\n}}\n"
    )
}

fn failing_source(marker: u128) -> String {
    format!(
        "/// Marks this run: {marker}.\npub fn add(left: u64, right: u64) -> u64 {{\n    let total: u32 = left + right;\n    total\n}}\n"
    )
}

/// The first lines of a result, with the account's email masked.
fn shown(result: &Value, lines: usize) -> String {
    let text = text_of(result);
    let masked: Vec<String> = text
        .lines()
        .take(lines)
        .map(|line| match line.strip_prefix("Account: ") {
            Some(_) => "Account: <the account>".to_string(),
            None => line.to_string(),
        })
        .collect();
    masked.join("\n    ")
}

#[tokio::test]
#[ignore = "live: set MACHINESTREAM_E2E=1 and MACHINESTREAM_API_KEY"]
async fn a_real_check_through_the_stdio_interface() {
    if std::env::var("MACHINESTREAM_E2E").as_deref() != Ok("1") {
        eprintln!("skipped: set MACHINESTREAM_E2E=1 to run the live test");
        return;
    }
    let key = std::env::var("MACHINESTREAM_API_KEY")
        .expect("MACHINESTREAM_API_KEY holds the key of the account to test with");
    let home = dirs::home_dir().expect("a home folder");
    let dir = tempfile::tempdir().unwrap();
    let marker = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .unwrap()
        .as_nanos();
    let project = tiny_crate(dir.path(), marker);

    // A clean environment and a throwaway home, with the toolchain still reachable: the
    // engine reports the local rustc version so the service can match it.
    let mut command = tokio::process::Command::new(env!("CARGO_BIN_EXE_machinestream-mcp"));
    command
        .env_clear()
        .env("PATH", std::env::var_os("PATH").unwrap_or_default())
        .env("HOME", dir.path().join("home"))
        .env(
            "RUSTUP_HOME",
            std::env::var_os("RUSTUP_HOME").unwrap_or_else(|| home.join(".rustup").into()),
        )
        .env(
            "CARGO_HOME",
            std::env::var_os("CARGO_HOME").unwrap_or_else(|| home.join(".cargo").into()),
        )
        .env("MACHINESTREAM_API_KEY", &key)
        .current_dir(&project)
        .kill_on_drop(true);
    if let Ok(url) = std::env::var("MACHINESTREAM_API_URL") {
        command.env("MACHINESTREAM_API_URL", url);
    }
    std::fs::create_dir_all(dir.path().join("home")).unwrap();
    let mut client = McpClient::start(command).await;

    println!("== tools/list");
    let list = client.request("tools/list", json!({})).await;
    let names: Vec<&str> = list["result"]["tools"]
        .as_array()
        .unwrap()
        .iter()
        .filter_map(|tool| tool["name"].as_str())
        .collect();
    println!("    {}", names.join(", "));
    assert!(names.starts_with(&["check", "check_parallel", "status", "setup", "run_output"]));

    println!("== status");
    let status = client.call("status", json!({})).await;
    println!("    {}", shown(&status, 4));
    assert_eq!(
        status["structuredContent"]["ready"], true,
        "the account is not ready: {}",
        status["structuredContent"]["next_step"]
    );

    println!("== check: cargo check");
    let started = Instant::now();
    let first = client
        .call_with_progress("check", json!({"command": "cargo check"}), "e2e-1")
        .await;
    println!("    {}", shown(&first, 2));
    println!(
        "    (call took {:.1} s; {} progress notification(s))",
        started.elapsed().as_secs_f64(),
        client.progress("e2e-1").len()
    );
    let structured = &first["structuredContent"];
    assert_eq!(
        structured["ran"], true,
        "not run remotely: {}",
        structured["reason"]
    );
    assert_eq!(structured["where"], "remote");
    assert_eq!(structured["exit_code"], 0, "{}", text_of(&first));
    assert_eq!(structured["passed"], true);
    assert_eq!(structured["cached"], false, "a new tree cannot be cached");
    assert!(structured["log_path"].is_string());
    assert_ne!(first["isError"], true);

    println!("== check: cargo check (exact repeat)");
    let repeat = client
        .call("check", json!({"command": "cargo check"}))
        .await;
    println!("    {}", shown(&repeat, 1));
    assert_eq!(
        repeat["structuredContent"]["cached"],
        true,
        "{}",
        text_of(&repeat)
    );
    assert_eq!(repeat["structuredContent"]["passed"], true);
    assert_eq!(
        repeat["structuredContent"]["billing"]["free_reason"],
        "cached"
    );
    assert_eq!(
        repeat["structuredContent"]["billing"]["credits_estimated"],
        0
    );

    println!("== check: cargo check (after a failing edit, uncommitted)");
    std::fs::write(project.join("src/lib.rs"), failing_source(marker)).unwrap();
    let failed = client
        .call("check", json!({"command": "cargo check"}))
        .await;
    println!("    {}", shown(&failed, 8));
    let structured = &failed["structuredContent"];
    assert_eq!(structured["ran"], true, "{}", structured["reason"]);
    assert_eq!(structured["passed"], false);
    assert_ne!(structured["exit_code"], 0);
    assert_ne!(failed["isError"], true, "a failed check is a result");
    let failures = structured["failures"].as_array().unwrap();
    assert!(
        !failures.is_empty(),
        "the compiler error was not extracted: {}",
        text_of(&failed)
    );
    println!("    failures: {}", serde_json::to_string(failures).unwrap());
    assert!(failures.iter().any(|failure| {
        failure["file"] == "src/lib.rs"
            && failure["line"] == 3
            && failure["message"]
                .as_str()
                .is_some_and(|message| message.contains("mismatched types"))
    }));
    assert!(text_of(&failed).contains("error[E0308]"));

    println!("== run_output: grep the saved run");
    let grep = client
        .call("run_output", json!({"grep": "^error", "max_lines": 5}))
        .await;
    println!("    {}", shown(&grep, 3));
    assert!(grep["structuredContent"]["matches"].as_u64().unwrap() >= 1);

    println!("== check_parallel: cargo check + cargo test (edit reverted)");
    std::fs::write(project.join("src/lib.rs"), passing_source(marker)).unwrap();
    let started = Instant::now();
    let parallel = client
        .call(
            "check_parallel",
            json!({"checks": [{"command": "cargo check"}, {"command": "cargo test"}]}),
        )
        .await;
    println!("    {}", shown(&parallel, 1));
    println!("    (call took {:.1} s)", started.elapsed().as_secs_f64());
    let structured = &parallel["structuredContent"];
    let checks = structured["checks"].as_array().unwrap();
    assert_eq!(checks.len(), 2);
    for check in checks {
        println!(
            "    {}: ran={} exit={} cached={} seconds={}",
            check["command"], check["ran"], check["exit_code"], check["cached"], check["seconds"]
        );
        assert_eq!(check["ran"], true, "{}", check["reason"]);
        assert_eq!(check["passed"], true);
    }
    assert_eq!(
        checks[0]["cached"], true,
        "cargo check on this exact tree ran before"
    );
    assert_eq!(
        checks[0]["tree"], checks[1]["tree"],
        "both commands ran on one snapshot"
    );
    assert_eq!(structured["summary"]["passed"], 2);
    client.stop().await;
    println!("== done");
}
